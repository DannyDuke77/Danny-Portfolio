import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import Script from "next/script";

import Navbar from "./components/Navbar";
import CVModal from "./components/modals/CVModal";
import ImagesModal from "./components/modals/ImagesModal";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "GITAU DANIEL NGIGE | Full Stack Developer",
  description:
    "Portfolio showcasing the projects and skills of Gitau Daniel Ngige, a proficient Full Stack Developer specializing in modern web technologies.",
};

export const viewport = {
  themeColor: "#000000",
  width: "device-width",
  initialScale: 1,
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" data-scroll-behavior="smooth" suppressHydrationWarning>
      <head>
        <Script
          id="theme-init"
          strategy="beforeInteractive"
          dangerouslySetInnerHTML={{
            __html: `
              try {
                var t = localStorage.getItem("theme");
                if (t === "dark" || (!t && window.matchMedia("(prefers-color-scheme: dark)").matches)) {
                  document.documentElement.classList.add("dark");
                }
              } catch (e) {}
            `,
          }}
        />
      </head>
      <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
        <Navbar />
        <main className="selection:bg-lime-700 selection:text-stone-50 dark:selection:bg-lime-300 dark:selection:text-black">
          {children}
          <CVModal />
          <ImagesModal />
        </main>
      </body>
    </html>
  );
}